// BioEcosystem - Early Ostracoderm Dual Armor Integrity (% OAI) & Hydrofoil Lift (% PEF) Telemetry
// Module: src/ui/telemetry_ostracoderm.js
// Version: 8.18.0 (Hour 538 - Looks & UI Agent: 104th Channel % PEF, Dual Ostracoderm HUD Dashboard)
// Zero emoji policy strictly enforced.

(function(global) {
    "use strict";

    /**
     * OstracodermTelemetryManager
     * High-precision laboratory telemetry tracking for early Ostracoderm / armored agnathan (Pteraspidomorphi, Thelodonti & Osteostraci) biology:
     * - Channel 103: Ostracoderm Armor Integrity Index (% OAI) - Hydroxyapatite aspidin shield cohesion, dermal plate thickness, mechanical crush deflection, and hydrodynamic denticles
     * - Channel 104: Pectoral Elevation & Hydrofoil Force Index (% PEF) - Paired hydrofoil angle of attack (AoA), Bernouilli dynamic lift, pitch trim equilibrium, and benthic ground effect
     * - Evaluates cephalic shield structural integrity [0.50 - 0.99] and acellular mineralized bone thickness [2.5 - 6.5 mm eq]
     * - Audits predatory crush resistance [0.45 - 0.85] and deflection of apex eurypterid pincer strikes
     * - Monitors microscopic dermal denticles [0.40 - 0.95] and laminar vortex boundary layer turbulence reduction
     * - Tracks heavy cephalic ballast negative buoyancy (1.2 - 3.8 N) and forward pitch tilt torque (0.25 - 0.75 N*m)
     * - Analyzes dynamic hydrofoil lift force (0.5 - 1.8 N) generated by early paired pectoral fin flaps with dynamic AoA (-5 to +25 deg)
     * - Audits pitch trim restorative moment (0.20 - 0.70 N*m) counteracting head-heavy dive torque
     * - Monitors benthic ground effect lift multiplier (1.00 - 1.40x) near the seafloor substrate
     * - Audits cephalic sensory fields acuity [0.65 - 0.95] and benthic detrital sediment mud filtration rate (0.25 - 0.65 mg/s)
     * - Implements 4 distinct biological regimes for both the 103rd (% OAI) and 104th (% PEF) telemetry channels
     * - Renders laboratory HUD indicators, telemetry status readouts, and circular history buffers
     */
    class OstracodermTelemetryManager {
        /**
         * Calculate dish-wide Ostracoderm anatomical, protective, and hydrodynamic metrics.
         * @param {Array<Object>} organisms - Live simulation organisms.
         * @param {Object} ostracodermManager - Global OstracodermArmorManager instance.
         * @param {number} tick - Current simulation tick.
         * @returns {Object} Comprehensive Ostracoderm telemetry metrics.
         */
        static calculateMetrics(organisms, ostracodermManager, tick) {
            let liveCount = 0;
            let ostCount = 0;
            let shieldedCount = 0;
            let benthicForagers = 0;
            let hydrofoilLiftCount = 0;

            let sumOAI = 0.0;
            let sumPEF = 0.0;
            let sumShield = 0.0;
            let sumThickness = 0.0;
            let sumCrush = 0.0;
            let sumDenticles = 0.0;
            let sumBuoyancy = 0.0;
            let sumPitchTorque = 0.0;
            let sumPectoralLift = 0.0;
            let sumAoA = 0.0;
            let sumHydrofoilLift = 0.0;
            let sumPitchTrim = 0.0;
            let sumGroundEffect = 0.0;
            let sumSensory = 0.0;
            let sumScanRate = 0.0;

            if (Array.isArray(organisms) && organisms.length > 0) {
                const len = organisms.length;
                for (let i = 0; i < len; i++) {
                    const org = organisms[i];
                    if (!org || org.isDead || org.alive === false) continue;
                    liveCount++;

                    if (org.isOstracoderm) {
                        ostCount++;

                        const oai = org.ostracodermArmorIntegrity !== undefined ? org.ostracodermArmorIntegrity : 65.0;
                        const pef = org.pectoralElevationForceIndex !== undefined ? org.pectoralElevationForceIndex : 35.0;
                        const shield = org.cephalicShieldIntegrity !== undefined ? org.cephalicShieldIntegrity : 0.88;
                        const thickness = org.dermalPlateThickness !== undefined ? org.dermalPlateThickness : 4.2;
                        const crush = org.crushResistanceCoeff !== undefined ? org.crushResistanceCoeff : 0.68;
                        const denticles = org.dermalDenticleDensity !== undefined ? org.dermalDenticleDensity : 0.72;
                        const buoyancy = org.negativeBuoyancyForce !== undefined ? org.negativeBuoyancyForce : 2.4;
                        const pitch = org.headHeavyPitchTorque !== undefined ? org.headHeavyPitchTorque : 0.48;
                        const pectoral = org.pectoralFinElevation !== undefined ? org.pectoralFinElevation : 1.5;
                        const aoa = org.pectoralAttackAngle !== undefined ? org.pectoralAttackAngle : 0.12;
                        const lift = org.hydrofoilLiftForce !== undefined ? org.hydrofoilLiftForce : 1.15;
                        const trim = org.pitchTrimCorrectionTorque !== undefined ? org.pitchTrimCorrectionTorque : 0.42;
                        const ground = org.benthicGroundEffectMultiplier !== undefined ? org.benthicGroundEffectMultiplier : 1.0;
                        const sensory = org.sensoryFieldAcuity !== undefined ? org.sensoryFieldAcuity : 0.82;
                        const scanRate = org.benthicDetritalScanningRate !== undefined ? org.benthicDetritalScanningRate : 0.42;

                        sumOAI += oai;
                        sumPEF += pef;
                        sumShield += shield;
                        sumThickness += thickness;
                        sumCrush += crush;
                        sumDenticles += denticles;
                        sumBuoyancy += buoyancy;
                        sumPitchTorque += pitch;
                        sumPectoralLift += pectoral;
                        sumAoA += aoa;
                        sumHydrofoilLift += lift;
                        sumPitchTrim += trim;
                        sumGroundEffect += ground;
                        sumSensory += sensory;
                        sumScanRate += scanRate;

                        if (shield >= 0.70) shieldedCount++;
                        if (org.y >= 140.0) benthicForagers++;
                        if (pectoral >= 1.2) hydrofoilLiftCount++;
                    }
                }
            }

            const ostracodermPrevalence = liveCount > 0 ? (ostCount / liveCount) * 100.0 : 0.0;
            const meanOAI = ostCount > 0 ? (sumOAI / ostCount) : 0.0;
            const meanPEF = ostCount > 0 ? (sumPEF / ostCount) : 0.0;
            const meanShield = ostCount > 0 ? (sumShield / ostCount) : 0.88;
            const meanThickness = ostCount > 0 ? (sumThickness / ostCount) : 4.2;
            const meanCrush = ostCount > 0 ? (sumCrush / ostCount) : 0.68;
            const meanDenticles = ostCount > 0 ? (sumDenticles / ostCount) : 0.72;
            const meanBuoyancy = ostCount > 0 ? (sumBuoyancy / ostCount) : 2.4;
            const meanPitchTorque = ostCount > 0 ? (sumPitchTorque / ostCount) : 0.48;
            const meanPectoralLift = ostCount > 0 ? (sumPectoralLift / ostCount) : 1.5;
            const meanAoA = ostCount > 0 ? (sumAoA / ostCount) : 0.12;
            const meanHydrofoilLift = ostCount > 0 ? (sumHydrofoilLift / ostCount) : 1.15;
            const meanPitchTrim = ostCount > 0 ? (sumPitchTrim / ostCount) : 0.42;
            const meanGroundEffect = ostCount > 0 ? (sumGroundEffect / ostCount) : 1.0;
            const meanSensory = ostCount > 0 ? (sumSensory / ostCount) : 0.82;
            const meanScanRate = ostCount > 0 ? (sumScanRate / ostCount) : 0.42;

            let crushDeflections = 0;
            let eurypteridSurvived = 0;
            let detritalScans = 0;
            let liftStabilizations = 0;
            let groundCruises = 0;
            let pitchTrimEvents = 0;
            let armoredBiomass = 0.0;

            if (ostracodermManager && ostracodermManager.getMetrics) {
                const mgr = ostracodermManager.getMetrics();
                crushDeflections = mgr.predatorCrushDeflections || 0;
                eurypteridSurvived = mgr.eurypteridPincerStrikesSurvived || 0;
                detritalScans = mgr.benthicDetritalScans || 0;
                liftStabilizations = mgr.hydrofoilLiftStabilizations || 0;
                groundCruises = mgr.groundEffectCruisingEvents || 0;
                pitchTrimEvents = mgr.pitchTrimStabilizations || 0;
                armoredBiomass = mgr.cumulativeArmoredBiomassAssimilated || 0.0;
            }

            // 4 Distinct Biological Regimes for 103rd Channel (% OAI)
            let regimeCodeOAI = "UNARMORED";
            let regimeTitleOAI = "UNARMORED & UNCALCIFIED CARTILAGE";
            let regimeBadgeOAI = "oai-unarmored";

            if (meanOAI >= 85.0) {
                regimeCodeOAI = "IMPENETRABLE";
                regimeTitleOAI = "IMPENETRABLE CEPHALIC CARAPACE";
                regimeBadgeOAI = "oai-impenetrable";
            } else if (meanOAI >= 60.0) {
                regimeCodeOAI = "ASPIDIN_ARMORED";
                regimeTitleOAI = "ASPIDIN SHIELD & HYDROFOIL BALANCED";
                regimeBadgeOAI = "oai-aspidin";
            } else if (meanOAI >= 30.0) {
                regimeCodeOAI = "DERMAL_SCALES";
                regimeTitleOAI = "DERMAL DENTICLES & FLEXIBLE PLATES";
                regimeBadgeOAI = "oai-dermal";
            }

            // 4 Distinct Biological Regimes for 104th Channel (% PEF)
            let regimeCodePEF = "STALLED";
            let regimeTitlePEF = "STALLED & NEGATIVE BALLAST DIVE";
            let regimeBadgePEF = "pef-stalled";

            if (meanPEF >= 85.0) {
                regimeCodePEF = "GROUND_CRUISE";
                regimeTitlePEF = "GROUND EFFECT CRUISE & PEAK LIFT";
                regimeBadgePEF = "pef-cruising";
            } else if (meanPEF >= 60.0) {
                regimeCodePEF = "STABLE_GLIDE";
                regimeTitlePEF = "STABLE HYDROFOIL GLIDE";
                regimeBadgePEF = "pef-gliding";
            } else if (meanPEF >= 30.0) {
                regimeCodePEF = "TRIMMING";
                regimeTitlePEF = "TRIMMING & INCIPIENT LIFT";
                regimeBadgePEF = "pef-trimming";
            }

            return {
                liveCount,
                ostCount,
                shieldedCount,
                benthicForagers,
                hydrofoilLiftCount,
                ostracodermPrevalence,
                meanOAI,
                meanPEF,
                meanShield,
                meanThickness,
                meanCrush,
                meanDenticles,
                meanBuoyancy,
                meanPitchTorque,
                meanPectoralLift,
                meanAoA,
                meanHydrofoilLift,
                meanPitchTrim,
                meanGroundEffect,
                meanSensory,
                meanScanRate,
                crushDeflections,
                eurypteridSurvived,
                detritalScans,
                liftStabilizations,
                groundCruises,
                pitchTrimEvents,
                armoredBiomass,
                regimeCodeOAI,
                regimeTitleOAI,
                regimeBadgeOAI,
                regimeCodePEF,
                regimeTitlePEF,
                regimeBadgePEF,
                tick
            };
        }

        /**
         * Update laboratory HUD telemetry readouts and status indicators for 103rd (% OAI) and 104th (% PEF) Channels.
         * @param {Object} metrics - Calculated Ostracoderm telemetry metrics.
         */
        static updateHUD(metrics) {
            if (!metrics) return;

            // 1. Primary Channel 103 Readout (% OAI - Ostracoderm Armor Integrity Index)
            const valOAIIndexEl = document.getElementById("valOAIIndex");
            if (valOAIIndexEl) {
                valOAIIndexEl.textContent = metrics.meanOAI.toFixed(1) + "% OAI (" + metrics.regimeTitleOAI + ")";
                if (metrics.meanOAI >= 85.0) {
                    valOAIIndexEl.style.color = "#fef3c7";
                } else if (metrics.meanOAI >= 60.0) {
                    valOAIIndexEl.style.color = "#fbbf24";
                } else if (metrics.meanOAI >= 30.0) {
                    valOAIIndexEl.style.color = "#d97706";
                } else {
                    valOAIIndexEl.style.color = "#ef4444";
                }
            }

            // 2. Secondary Channel 103 Status
            const valOAIStatusEl = document.getElementById("valOAIStatus");
            if (valOAIStatusEl) {
                valOAIStatusEl.textContent =
                    "OSTRACODERM: " + metrics.ostCount + "/" + metrics.liveCount +
                    " (" + metrics.ostracodermPrevalence.toFixed(0) + "%) | SHIELD: " + (metrics.meanShield * 100.0).toFixed(0) + "%" +
                    " | PLATES: " + metrics.meanThickness.toFixed(1) + " mm" +
                    " | CRUSH: " + (metrics.meanCrush * 100.0).toFixed(0) + "%" +
                    " | DENTICLES: " + (metrics.meanDenticles * 100.0).toFixed(0) + "%" +
                    " | BUOYANCY: -" + metrics.meanBuoyancy.toFixed(1) + " N" +
                    " | LIFT: " + metrics.meanPectoralLift.toFixed(1) + " N" +
                    " | DEFLECTIONS: " + metrics.crushDeflections;
                valOAIStatusEl.style.color = metrics.meanOAI >= 50.0 ? "#fbbf24" : "#d97706";
            }

            // 3. Primary Channel 104 Readout (% PEF - Pectoral Elevation & Hydrofoil Force Index)
            const valPEFIndexEl = document.getElementById("valPEFIndex");
            if (valPEFIndexEl) {
                valPEFIndexEl.textContent = metrics.meanPEF.toFixed(1) + "% PEF (" + metrics.regimeTitlePEF + ")";
                if (metrics.meanPEF >= 85.0) {
                    valPEFIndexEl.style.color = "#a5f3fc";
                } else if (metrics.meanPEF >= 60.0) {
                    valPEFIndexEl.style.color = "#06b6d4";
                } else if (metrics.meanPEF >= 30.0) {
                    valPEFIndexEl.style.color = "#38bdf8";
                } else {
                    valPEFIndexEl.style.color = "#ef4444";
                }
            }

            // 4. Secondary Channel 104 Status
            const valPEFStatusEl = document.getElementById("valPEFStatus");
            if (valPEFStatusEl) {
                valPEFStatusEl.textContent =
                    "PEF: " + metrics.meanPEF.toFixed(1) + "%" +
                    " | AoA: " + (metrics.meanAoA * (180 / Math.PI)).toFixed(1) + " deg" +
                    " | LIFT: " + metrics.meanHydrofoilLift.toFixed(2) + " N" +
                    " | TRIM: " + metrics.meanPitchTrim.toFixed(2) + " N*m" +
                    " | GROUND: " + metrics.meanGroundEffect.toFixed(2) + "x" +
                    " | GLIDES: " + metrics.liftStabilizations +
                    " | CRUISE: " + metrics.groundCruises;
                valPEFStatusEl.style.color = metrics.meanPEF >= 50.0 ? "#a5f3fc" : "#06b6d4";
            }

            // 5. Dedicated Ostracoderm Laboratory HUD Badges (if DOM present)
            const valOAIBadgeEl = document.getElementById("valOAIBadge");
            if (valOAIBadgeEl) {
                valOAIBadgeEl.className = "oai-badge " + metrics.regimeBadgeOAI;
                valOAIBadgeEl.textContent = metrics.regimeCodeOAI;
            }

            const valPEFBadgeEl = document.getElementById("valPEFBadge");
            if (valPEFBadgeEl) {
                valPEFBadgeEl.className = "pef-badge " + metrics.regimeBadgePEF;
                valPEFBadgeEl.textContent = metrics.regimeCodePEF;
            }

            const valOAIMeterFillEl = document.getElementById("valOAIMeterFill");
            if (valOAIMeterFillEl) {
                valOAIMeterFillEl.style.width = Math.max(0, Math.min(100, metrics.meanOAI)).toFixed(1) + "%";
                valOAIMeterFillEl.style.backgroundColor = metrics.meanOAI >= 60.0 ? "#d97706" : "#f59e0b";
            }

            const valPEFMeterFillEl = document.getElementById("valPEFMeterFill");
            if (valPEFMeterFillEl) {
                valPEFMeterFillEl.style.width = Math.max(0, Math.min(100, metrics.meanPEF)).toFixed(1) + "%";
                valPEFMeterFillEl.style.backgroundColor = metrics.meanPEF >= 60.0 ? "#06b6d4" : "#38bdf8";
            }
        }

        /**
         * Record telemetry metrics to historical circular buffers for graphing.
         * @param {Object} historyData - Simulation history recording buffers.
         * @param {Object} metrics - Calculated telemetry metrics.
         */
        static recordHistory(historyData, metrics) {
            if (!historyData) return;

            // 103rd Channel: % OAI
            if (!historyData.ostracodermArmorIntegrity) {
                historyData.ostracodermArmorIntegrity = new Array(74).fill(0);
            }
            const chartValOAI = Number.isFinite(metrics.meanOAI) ?
                Math.max(0, Math.min(100, metrics.meanOAI)) : 0;
            historyData.ostracodermArmorIntegrity.shift();
            historyData.ostracodermArmorIntegrity.push(chartValOAI);

            // 104th Channel: % PEF
            if (!historyData.pectoralElevationForceIndex) {
                historyData.pectoralElevationForceIndex = new Array(74).fill(0);
            }
            const chartValPEF = Number.isFinite(metrics.meanPEF) ?
                Math.max(0, Math.min(100, metrics.meanPEF)) : 0;
            historyData.pectoralElevationForceIndex.shift();
            historyData.pectoralElevationForceIndex.push(chartValPEF);
        }

        /**
         * Execute a complete telemetry cycle: calculation, HUD update, and history recording.
         * @param {Array<Object>} organisms - Live simulation organisms.
         * @param {Object} historyData - Simulation history recording buffers.
         * @param {Object} ostracodermManager - Global OstracodermArmorManager instance.
         * @param {number} tick - Current simulation tick.
         * @returns {Object} Calculated telemetry metrics.
         */
        static step(organisms, historyData, ostracodermManager, tick) {
            const metrics = OstracodermTelemetryManager.calculateMetrics(organisms, ostracodermManager, tick);
            OstracodermTelemetryManager.updateHUD(metrics);
            OstracodermTelemetryManager.recordHistory(historyData, metrics);
            return metrics;
        }
    }

    if (typeof module !== "undefined" && module.exports) {
        module.exports = OstracodermTelemetryManager;
    }
    if (typeof global !== "undefined") {
        global.OstracodermTelemetryManager = OstracodermTelemetryManager;
    }
})(typeof window !== "undefined" ? window : global);

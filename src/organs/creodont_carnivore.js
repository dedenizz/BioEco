(function(global) {
    "use strict";

    /**
     * CreodontCarnivoreManager
     * High-fidelity biological simulation of Early Tertiary (Paleocene-Eocene-Oligocene) Apex Terrestrial Carnivores:
     * - Evolutionary Stage & Lineages (*Mesonychia* - *Mesonyx*, *Dissopsalis*, *Andrewsarchus*;
     *   *Hyaenodonta* / *Creodonta* - *Hyaenodon*, *Sarkastodon*, *Sinopa*):
     *   The dominant hypercarnivorous terrestrial mammals radiating in the wake of dinosaur extinction,
     *   evolving apex predatory adaptations to hunt and process multi-ton megaherbivores (*Coryphodon*, *Uintatherium*).
     * - Craniomandibular Bite Force & Bone-Crushing Carnassial Shearing:
     *   Massive craniomandibular bite forces (craniomandibularBiteForce: 1800 - 3500 N) generated by hypertrophied
     *   temporalis and masseter musculature anchoring onto towering sagittal crests and expanded zygomatic arches.
     *   Specialized carnassial shearing blades (carnassialShearingEfficiency: 0.70 - 0.98) formed by opposing premolars
     *   and molars (P4/M1 or M1/M2/M3) acting as self-sharpening scissor shears that cleave tough hides and heavy tendons.
     *   Decussating prismatic enamel ultrastructure (prismaticEnamelResilience: 0.72 - 0.96) resisting catastrophic tooth
     *   fracture, enamel delamination, and longitudinal splitting under multi-thousand-Newton crushing loads.
     *   Active cortical bone shattering and high-energy lipid assimilation from cancellous marrow
     *   (boneMarrowExtractionRate: 0.65 - 0.95).
     * - Cursorial Digitigrade Stance & Elastic Tendon Recoil:
     *   Evolution from archaic plantigrade flat-footedness into elevated digitigrade cursorial limb posture
     *   (digitigradeStrideEfficiency: 0.72 - 0.96), with lengthened metapodials and compacted ankle joints.
     *   High-efficiency kinetic energy storage and return within heavy calcaneal Achilles tendon complexes
     *   (elasticTendonRecoil: 0.60 - 0.92), driving explosive sprint acceleration (cursorialPursuitVelocity: 1.8 - 4.2 px/tick)
     *   across open Eocene floodplain savanna and riparian gallery forests.
     * - Hypercarnivore Gastric Acid Barrier & Scavenging Resilience:
     *   Extreme gastric acidification (gastricAcidBarrierPH: 1.2 - 1.8) capable of dissolving demineralized bone matrix,
     *   hydrolyzing calcified cartilage collagen, and establishing a sterile chemical barrier that annihilates putrefactive
     *   bacterial pathogens (scavengingToxinResilience: 0.70 - 0.96) found in sun-baked multi-ton carrion.
     *   Hyper-developed olfactory bulbs and cribriform ethmoid turbinates yielding long-range carrion scent tracking
     *   (olfactoryTrackingRange: 0.75 - 0.98).
     * - 135th Telemetry Channel: % BCI (Bone-Crushing & Carnassial Index) mathematical core.
     * - 136th Telemetry Channel: % CTI (Cursorial Terrestrial Index) mathematical core.
     */
    class CreodontCarnivoreManager {
        constructor() {
            this.baseBiteForce = 2650.0;                   // [1800 - 3500 N]
            this.baseCarnassialShear = 0.84;               // [0.70 - 0.98]
            this.baseEnamelResilience = 0.85;              // [0.72 - 0.96]
            this.baseMarrowExtraction = 0.80;              // [0.65 - 0.95]

            this.baseDigitigradeStride = 0.84;             // [0.72 - 0.96]
            this.baseElasticRecoil = 0.78;                 // [0.60 - 0.92]
            this.basePursuitVelocity = 2.85;               // [1.8 - 4.2 px/tick]

            this.baseGastricPH = 1.45;                     // [1.2 - 1.8]
            this.baseScavengingResilience = 0.84;          // [0.70 - 0.96]
            this.baseOlfactoryRange = 0.86;                // [0.75 - 0.98]

            this.metrics = {
                totalLiveCells: 0,
                totalApexCarnivores: 0,
                totalCreodonts: 0,
                totalMesonychids: 0,
                activePursuitSprinters: 0,
                activeBoneCrushingStrikes: 0,
                meanBoneCrushingIndex: 0.0,                 // 135th Channel % BCI
                meanCursorialTerrestrialIndex: 0.0,         // 136th Channel % CTI
                meanBiteForce: 2650.0,
                meanCarnassialShear: 0.84,
                meanEnamelResilience: 0.85,
                meanMarrowExtraction: 0.80,
                meanDigitigradeStride: 0.84,
                meanElasticRecoil: 0.78,
                meanPursuitVelocity: 2.85,
                meanGastricPH: 1.45,
                meanScavengingResilience: 0.84,
                meanOlfactoryRange: 0.86,
                boneCrushEvents: 0,
                carnassialShearEvents: 0,
                pursuitSprintEvents: 0,
                scavengingAssimilationYield: 0.0,
                cumulativeCarnivoreBiomass: 0.0
            };

            this.carcassDecayTroughPool = 150.0;
        }

        /**
         * Initialize or upgrade an organism's Apex Carnivore traits.
         * @param {Object} org - Organism instance.
         */
        initOrganism(org) {
            if (!org) return;

            if (org.isApexCarnivore === undefined) {
                const isCarnivorous = org.dna && (org.dna.diet === "CARNIVORE" || org.dna.diet === "PREDATOR");
                const isMammalian = org.isTribosphenic || org.isChorioallantoic || org.isEutherian ||
                                    org.isTherian || org.isSynapsid || isCarnivorous;
                org.isApexCarnivore = isMammalian && (org.diet === "CARNIVORE" || Math.random() < 0.45);
            }

            if (org.isCreodont === undefined) {
                org.isCreodont = org.isApexCarnivore && Math.random() < 0.60;
            }
            if (org.isMesonychid === undefined) {
                org.isMesonychid = org.isApexCarnivore && !org.isCreodont && Math.random() < 0.75;
            }

            // Craniomandibular Bite Force & Dental traits
            if (org.craniomandibularBiteForce === undefined) {
                org.craniomandibularBiteForce = org.isApexCarnivore ?
                    (2000.0 + Math.random() * 1400.0) : (450.0 + Math.random() * 600.0);
            }
            if (org.carnassialShearingEfficiency === undefined) {
                org.carnassialShearingEfficiency = org.isApexCarnivore ?
                    (0.74 + Math.random() * 0.22) : (0.20 + Math.random() * 0.30);
            }
            if (org.prismaticEnamelResilience === undefined) {
                org.prismaticEnamelResilience = org.isApexCarnivore ?
                    (0.75 + Math.random() * 0.20) : (0.25 + Math.random() * 0.25);
            }
            if (org.boneMarrowExtractionRate === undefined) {
                org.boneMarrowExtractionRate = org.isApexCarnivore ?
                    (0.70 + Math.random() * 0.24) : (0.15 + Math.random() * 0.25);
            }

            // Cursorial Digitigrade Stance & Tendon traits
            if (org.digitigradeStrideEfficiency === undefined) {
                org.digitigradeStrideEfficiency = org.isApexCarnivore ?
                    (0.74 + Math.random() * 0.21) : (0.20 + Math.random() * 0.30);
            }
            if (org.elasticTendonRecoil === undefined) {
                org.elasticTendonRecoil = org.isApexCarnivore ?
                    (0.65 + Math.random() * 0.25) : (0.20 + Math.random() * 0.25);
            }
            if (org.cursorialPursuitVelocity === undefined) {
                org.cursorialPursuitVelocity = org.isApexCarnivore ?
                    (2.2 + Math.random() * 1.8) : (0.9 + Math.random() * 0.9);
            }

            // Hypercarnivore Gastric & Olfactory traits
            if (org.gastricAcidBarrierPH === undefined) {
                org.gastricAcidBarrierPH = org.isApexCarnivore ?
                    (1.25 + Math.random() * 0.45) : (2.4 + Math.random() * 0.9);
            }
            if (org.scavengingToxinResilience === undefined) {
                org.scavengingToxinResilience = org.isApexCarnivore ?
                    (0.73 + Math.random() * 0.22) : (0.20 + Math.random() * 0.25);
            }
            if (org.olfactoryTrackingRange === undefined) {
                org.olfactoryTrackingRange = org.isApexCarnivore ?
                    (0.76 + Math.random() * 0.21) : (0.25 + Math.random() * 0.25);
            }

            // Dynamic states
            if (org.boneCrushingCarnassialIndex === undefined) {
                org.boneCrushingCarnassialIndex = this.calculateBCI(org);
            }
            if (org.cursorialTerrestrialIndex === undefined) {
                org.cursorialTerrestrialIndex = this.calculateCTI(org);
            }

            if (org.dentalProrationWear === undefined) {
                org.dentalProrationWear = 0.0;
            }
            if (org.marrowLipidReserve === undefined) {
                org.marrowLipidReserve = 30.0 + Math.random() * 40.0;
            }
            if (org.isPursuitSprinting === undefined) {
                org.isPursuitSprinting = false;
            }
            if (org.isCraniomandibularStriking === undefined) {
                org.isCraniomandibularStriking = false;
            }
            if (org.targetPreyId === undefined) {
                org.targetPreyId = null;
            }
        }

        /**
         * Calculate 135th Channel: Bone-Crushing & Carnassial Index (% BCI)
         * Formulated based on craniomandibular bite force, carnassial shearing efficiency,
         * bone marrow extraction rate, and concentrated gastric acid pH barrier.
         * @param {Object} org - Organism instance.
         * @returns {number} Value in range [0, 100].
         */
        calculateBCI(org) {
            if (!org) return 0.0;
            const bf = Math.max(0.0, Math.min(3500.0, org.craniomandibularBiteForce || 500.0)) / 3500.0;
            const shear = Math.max(0.0, Math.min(1.0, org.carnassialShearingEfficiency || 0.20));
            const marrow = Math.max(0.0, Math.min(1.0, org.boneMarrowExtractionRate || 0.15));
            const ph = Math.max(1.0, Math.min(3.0, org.gastricAcidBarrierPH || 2.5));
            const acid = Math.max(0.0, Math.min(1.0, (2.0 - ph) / 0.8 + 0.25));

            const raw = (bf * 0.35 + shear * 0.30 + marrow * 0.20 + acid * 0.15) * 100.0;
            return Math.max(0.0, Math.min(100.0, raw));
        }

        /**
         * Calculate 136th Channel: Cursorial Terrestrial Index (% CTI)
         * Formulated based on digitigrade stride efficiency, elastic tendon recoil,
         * and cursorial pursuit sprinting velocity.
         * @param {Object} org - Organism instance.
         * @returns {number} Value in range [0, 100].
         */
        calculateCTI(org) {
            if (!org) return 0.0;
            const stride = Math.max(0.0, Math.min(1.0, org.digitigradeStrideEfficiency || 0.20));
            const recoil = Math.max(0.0, Math.min(1.0, org.elasticTendonRecoil || 0.20));
            const vel = Math.max(0.0, Math.min(4.2, org.cursorialPursuitVelocity || 1.0)) / 4.2;

            const raw = (stride * 0.40 + recoil * 0.35 + vel * 0.25) * 100.0;
            return Math.max(0.0, Math.min(100.0, raw));
        }

        /**
         * Determine biological regime for Bone-Crushing & Carnassial Shearing (% BCI).
         * @param {number} bci - Percent index.
         * @returns {string} Regime tag.
         */
        getBCIRegime(bci) {
            if (bci < 25.0) return "BLUNT_DENTITION_BASAL";
            if (bci < 50.0) return "INCIPIENT_SECTORIAL_SHEAR";
            if (bci < 75.0) return "ADVANCED_CREODONT_BONEBREAKER";
            return "APEX_MESONYCHID_CRUSHER";
        }

        /**
         * Determine biological regime for Cursorial Terrestrial Locomotion (% CTI).
         * @param {number} cti - Percent index.
         * @returns {string} Regime tag.
         */
        getCTIRegime(cti) {
            if (cti < 25.0) return "PLANTIGRADE_AMBLING";
            if (cti < 50.0) return "SEMI_DIGITIGRADE_PROWLER";
            if (cti < 75.0) return "DIGITIGRADE_SPRINTER";
            return "APEX_CURSORIAL_CHASER";
        }

        /**
         * Update physics, kinematics, and predator-prey dynamics for all organisms.
         * @param {Array<Object>} organisms - Live cell array.
         * @param {number} dt - Timestep delta.
         * @param {number} boundsWidth - Simulation canvas width.
         * @param {number} boundsHeight - Simulation canvas height.
         */
        updateAll(organisms, dt, boundsWidth, boundsHeight) {
            if (!Array.isArray(organisms) || organisms.length === 0) return;

            let liveCount = 0;
            let apexCount = 0;
            let creoCount = 0;
            let mesoCount = 0;
            let sprintCount = 0;
            let strikeCount = 0;

            let sumBCI = 0.0;
            let sumCTI = 0.0;
            let sumBiteForce = 0.0;
            let sumCarnassialShear = 0.0;
            let sumEnamelResilience = 0.0;
            let sumMarrowExtraction = 0.0;
            let sumDigitigradeStride = 0.0;
            let sumElasticRecoil = 0.0;
            let sumPursuitVelocity = 0.0;
            let sumGastricPH = 0.0;
            let sumScavengingResilience = 0.0;
            let sumOlfactoryRange = 0.0;
            let totalApexBiomass = 0.0;

            const n = organisms.length;

            for (let i = 0; i < n; i++) {
                const org = organisms[i];
                if (!org || org.isDead) continue;
                liveCount++;

                this.initOrganism(org);

                // Compute telemetry metrics per cell
                const bci = this.calculateBCI(org);
                const cti = this.calculateCTI(org);
                org.boneCrushingCarnassialIndex = bci;
                org.cursorialTerrestrialIndex = cti;

                sumBCI += bci;
                sumCTI += cti;

                if (org.isApexCarnivore) {
                    apexCount++;
                    if (org.isCreodont) creoCount++;
                    if (org.isMesonychid) mesoCount++;

                    sumBiteForce += (org.craniomandibularBiteForce || this.baseBiteForce);
                    sumCarnassialShear += (org.carnassialShearingEfficiency || this.baseCarnassialShear);
                    sumEnamelResilience += (org.prismaticEnamelResilience || this.baseEnamelResilience);
                    sumMarrowExtraction += (org.boneMarrowExtractionRate || this.baseMarrowExtraction);
                    sumDigitigradeStride += (org.digitigradeStrideEfficiency || this.baseDigitigradeStride);
                    sumElasticRecoil += (org.elasticTendonRecoil || this.baseElasticRecoil);
                    sumPursuitVelocity += (org.cursorialPursuitVelocity || this.basePursuitVelocity);
                    sumGastricPH += (org.gastricAcidBarrierPH || this.baseGastricPH);
                    sumScavengingResilience += (org.scavengingToxinResilience || this.baseScavengingResilience);
                    sumOlfactoryRange += (org.olfactoryTrackingRange || this.baseOlfactoryRange);

                    totalApexBiomass += (org.radius || 15.0) * (org.energy || 50.0) * 0.02;

                    // 1. Olfactory Tracking & Pursuit Target Acquisition
                    let nearestPrey = null;
                    let minDistSq = 28000.0 * (org.olfactoryTrackingRange || 0.85);

                    for (let j = 0; j < n; j++) {
                        if (i === j) continue;
                        const potentialPrey = organisms[j];
                        if (!potentialPrey || potentialPrey.isDead) continue;

                        // Target herbivores, megaherbivores, or weaker organisms
                        if (potentialPrey.isMegaherbivore || potentialPrey.dna?.diet === "HERBIVORE" ||
                            (potentialPrey.energy && potentialPrey.energy < org.energy * 0.8)) {
                            const dx = potentialPrey.x - org.x;
                            const dy = potentialPrey.y - org.y;
                            const dSq = dx * dx + dy * dy;
                            if (dSq < minDistSq) {
                                minDistSq = dSq;
                                nearestPrey = potentialPrey;
                            }
                        }
                    }

                    // 2. Cursorial Digitigrade Pursuit & Sprint
                    if (nearestPrey && minDistSq > 225.0) {
                        org.isPursuitSprinting = true;
                        sprintCount++;
                        this.metrics.pursuitSprintEvents++;

                        const dist = Math.sqrt(minDistSq) || 1.0;
                        const dirX = (nearestPrey.x - org.x) / dist;
                        const dirY = (nearestPrey.y - org.y) / dist;

                        // Sprint velocity boosted by digitigrade stride & tendon recoil
                        const sprintSpeed = (org.cursorialPursuitVelocity || 2.85) *
                            (0.8 + (org.elasticTendonRecoil || 0.78) * 0.5);

                        org.vx = (org.vx || 0) * 0.85 + dirX * sprintSpeed * 0.15;
                        org.vy = (org.vy || 0) * 0.85 + dirY * sprintSpeed * 0.15;

                        // Metabolic cost offset by elastic tendon energy return
                        const metabolicCost = (0.015 * (1.0 - (org.elasticTendonRecoil || 0.78) * 0.4));
                        org.energy = Math.max(5.0, (org.energy || 50.0) - metabolicCost);
                    } else {
                        org.isPursuitSprinting = false;
                    }

                    // 3. Bone-Crushing Bite Strike & Carnassial Shearing
                    if (nearestPrey && minDistSq <= 225.0) {
                        org.isCraniomandibularStriking = true;
                        strikeCount++;
                        this.metrics.carnassialShearEvents++;

                        // Bite strike mechanics
                        const biteForce = org.craniomandibularBiteForce || 2650.0;
                        const shearEff = org.carnassialShearingEfficiency || 0.84;
                        const enamelRes = org.prismaticEnamelResilience || 0.85;
                        const marrowRate = org.boneMarrowExtractionRate || 0.80;

                        // Damage dealt to prey (scaled by bite force and shear efficiency)
                        const damage = (biteForce / 250.0) * shearEff;
                        nearestPrey.energy = Math.max(0.0, (nearestPrey.energy || 50.0) - damage);

                        // High-calorie marrow and lipid extraction
                        const marrowYield = damage * marrowRate * 0.65;
                        org.energy = Math.min(260.0, (org.energy || 50.0) + marrowYield);
                        org.marrowLipidReserve = Math.min(100.0, (org.marrowLipidReserve || 30.0) + marrowYield * 0.4);

                        this.metrics.scavengingAssimilationYield += marrowYield;
                        this.metrics.boneCrushEvents++;

                        // Enamel wear check: pristine decussating prisms prevent dental failure
                        if (Math.random() > enamelRes) {
                            org.dentalProrationWear = (org.dentalProrationWear || 0.0) + 0.02;
                        }

                        // Satiation / Kill handling
                        if (nearestPrey.energy <= 0.0) {
                            nearestPrey.isDead = true;
                            nearestPrey.causeOfDeath = "KILLED_BY_APEX_CREODONT";
                        }
                    } else {
                        org.isCraniomandibularStriking = false;
                    }

                    // 4. Hypercarnivore Gastric Bone Dissolution & Pathogen Neutralization
                    // Constant processing of ingested bone shards and connective tissues
                    if (org.marrowLipidReserve && org.marrowLipidReserve > 5.0) {
                        const acidPH = org.gastricAcidBarrierPH || 1.45;
                        const dissolutionRate = (2.2 - acidPH) * 0.12;
                        const digestedEnergy = Math.min(org.marrowLipidReserve, dissolutionRate);
                        org.marrowLipidReserve -= digestedEnergy;
                        org.energy = Math.min(260.0, (org.energy || 50.0) + digestedEnergy * 1.5);
                    }
                }
            }

            // Aggregate metrics
            this.metrics.totalLiveCells = liveCount;
            this.metrics.totalApexCarnivores = apexCount;
            this.metrics.totalCreodonts = creoCount;
            this.metrics.totalMesonychids = mesoCount;
            this.metrics.activePursuitSprinters = sprintCount;
            this.metrics.activeBoneCrushingStrikes = strikeCount;

            this.metrics.meanBoneCrushingIndex = liveCount > 0 ? (sumBCI / liveCount) : 0.0;
            this.metrics.meanCursorialTerrestrialIndex = liveCount > 0 ? (sumCTI / liveCount) : 0.0;

            this.metrics.meanBiteForce = apexCount > 0 ? (sumBiteForce / apexCount) : this.baseBiteForce;
            this.metrics.meanCarnassialShear = apexCount > 0 ? (sumCarnassialShear / apexCount) : this.baseCarnassialShear;
            this.metrics.meanEnamelResilience = apexCount > 0 ? (sumEnamelResilience / apexCount) : this.baseEnamelResilience;
            this.metrics.meanMarrowExtraction = apexCount > 0 ? (sumMarrowExtraction / apexCount) : this.baseMarrowExtraction;
            this.metrics.meanDigitigradeStride = apexCount > 0 ? (sumDigitigradeStride / apexCount) : this.baseDigitigradeStride;
            this.metrics.meanElasticRecoil = apexCount > 0 ? (sumElasticRecoil / apexCount) : this.baseElasticRecoil;
            this.metrics.meanPursuitVelocity = apexCount > 0 ? (sumPursuitVelocity / apexCount) : this.basePursuitVelocity;
            this.metrics.meanGastricPH = apexCount > 0 ? (sumGastricPH / apexCount) : this.baseGastricPH;
            this.metrics.meanScavengingResilience = apexCount > 0 ? (sumScavengingResilience / apexCount) : this.baseScavengingResilience;
            this.metrics.meanOlfactoryRange = apexCount > 0 ? (sumOlfactoryRange / apexCount) : this.baseOlfactoryRange;

            this.metrics.cumulativeCarnivoreBiomass = totalApexBiomass;
        }

        /**
         * Simulation step entrypoint.
         * @param {Array<Object>} organisms - Live organisms array.
         * @param {number} tick - Simulation tick counter.
         */
        step(organisms, tick) {
            const w = (typeof canvas !== "undefined" && canvas && canvas.width) ? canvas.width : 660;
            const h = (typeof canvas !== "undefined" && canvas && canvas.height) ? canvas.height : 660;
            this.updateAll(organisms, 0.016, w, h);
        }

        /**
         * Return current simulation audit metrics.
         * @returns {Object} Comprehensive Apex Carnivore metrics.
         */
        getMetrics() {
            return Object.assign({}, this.metrics);
        }
    }

    if (typeof module !== "undefined" && module.exports) {
        module.exports = CreodontCarnivoreManager;
    }
    if (typeof global !== "undefined") {
        global.CreodontCarnivoreManager = CreodontCarnivoreManager;
        global.creodontCarnivoreManager = new CreodontCarnivoreManager();
    }
})(typeof window !== "undefined" ? window : global);
